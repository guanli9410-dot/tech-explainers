function typeLabel(type) {
  return { system: '系统类 · 搭建序列', route: '路线类 · 发展图解', generic: '通用类 · 双视角' }[type] || '思维导图';
}

/* ---------- 生成整图的系统提示词 ---------- */
function buildGenerateSystemPrompt(audienceLabel) {
  return `你是一个"拷问式拆解引擎"：用户给你一个主题，你要像一位严苛但说人话的老师，把这个主题拷问透，产出一棵可教学的思维导图。拷问的追问链：这个东西解决什么问题？它怎么来的/怎么构建？运行起来发生什么？什么时候会坏？

## 第一步：判定主题类型（三选一，写入输出 type 字段）
- system 系统类：可被设计搭建的东西（软件栈、模型、算法、管线、架构、产品、组织机制）→ 用"搭建序列"骨架
- route 路线类：有代际演进、尚无胜者的领域（电池、电机、技术路线之争、行业格局）→ 用"发展图解"骨架
- generic 通用类：概念、学科、技能等不属于上两类 → 用"通用双视角"骨架

## 骨架规范（主干节点必须按此组织）
【系统类 · 搭建序列】
- 主干 = 步骤序列：从"骨架（最小可动物）"开始，每一步加一块功能/一层结构，从简单到复杂（按架构复杂度排，不按编年史）
- 每个步骤主干节点必须带 demand 字段 = 需求句：≤50字，说清"这一步要实现什么 + 上一步留下了什么限制"，句式如"需求：……——……"
- 最后一个主干节点是「一次实际运行」：挑一个真实小任务，子节点是它从头走到尾的关键时刻（动态视角）
【路线类 · 发展图解】
- 主干 = 起点 → 各代演进 → 前沿站：起点必须带参照系（被替换的对手或被继承的前身）；每代演进说清"解决了什么、固化了什么新约束"；前沿站若无胜者则并列各条路线（主张/软肋/阵营）
- 最后一个主干节点是「一次穿线」：同一个任务让各条路线各做一遍、各自卡在哪里（动态视角）
【通用类 · 双视角】
- 主干固定四支：①它解决什么问题（没有它会怎样）→ ②静态视角：怎么构建/由什么组成 → ③动态视角：运行/发生起来是什么过程（跟一次真实过程从头到尾）→ ④边界与失效：什么时候不管用、常见误区

## 所有类型公共硬规则（最高优先级，逐条自查）
1. 读者水平：${audienceLabel}——默认读者至少在某部分是初学者。任何专业术语第一次出现时，必须在 note 里用一句大白话解释，不许假设读者已经知道
2. 只用该领域公认的标准术语（通用中文译名，可括注英文原词）；严禁发明新词、生造缩写、把比喻当术语名
3. 说人话：不用论文腔和行业黑话；比喻整棵树最多出现一次
4. 凡断言"X 是瓶颈 / Y 打破瓶颈 / Z 更优"，必须就地给一个定量量级例子（数字口径粗略即可），不许只给定性说法
5. 概念先立后用：子节点可以用父辈链上已解释过的术语；不许用还没出现过的术语做节点标题
6. 模型/学习系统类主题必须覆盖 训练—部署—推理 三个生命周期；实物/器件类主题必须覆盖 制造—使用 两幕
7. 拷问式拆分：一个概念两三句话讲得完就不拆子节点；讲不完才拆成子节点继续讲——拆解是兜底，不是默认

## 节点规模
- 主干 4~7 个；总节点 18~40 个；最深 4 层（不含根）
- title ≤ 16 字；note 每条 1~3 句大白话

## 输出格式
只输出一个 JSON 对象，不要 markdown 代码围栏，不要任何其它文字：
{"type":"system|route|generic","tree":{"title":"主题名","note":"一句话总括","demand":"","children":[...]}}
每个节点：{"title":"节点名","demand":"需求句，仅步骤/主干节点需要，其他留空字符串","note":"1-3句大白话解释","children":[]}`;
}

function buildGenerateUserMessage(topic, audienceLabel, goal) {
  let msg = `主题：${topic}\n读者水平：${audienceLabel}`;
  if (goal && goal.trim()) msg += `\n学习目的：${goal.trim()}（组织顺序和取舍向这个目的倾斜）`;
  msg += `\n\n请拷问这个主题并输出思维导图 JSON。`;
  return msg;
}

/* ---------- 追问生成子树 ---------- */
function buildExpandMessages(map, node, chainTitles, question) {
  const chain = chainTitles.map((t, i) => `${'　'.repeat(i)}${t}`).join('\n');
  const siblings = (node.children || []).map((c) => c.title).join('、') || '（还没有子节点）';
  const q = question && question.trim()
    ? `用户的追问：${question.trim()}`
    : '用户没有指定追问——请按拷问链条（为什么需要/怎么构建/运行起来什么样/什么时候会坏）挑这个节点当前最该被追问的方向。';

  const system = `你在一棵"拷问式思维导图"上为一个节点追加子树。方法论与硬规则：
1. 只用领域公认标准术语，严禁发明新词或生造缩写；首次出现的术语在 note 里用一句大白话解释（读者：${audienceLabelOf(map)}）
2. 说人话，不用论文腔；定量断言必须配一个量级例子
3. 概念先立后用；两三句讲得完就不拆子节点
4. 如实给出边界、失效与误区，不要只说好话
5. 子节点之间不重复、不与已有子节点重复
只输出 JSON：{"children":[{...}]}，不要围栏和其它文字。节点结构：{"title":"≤16字","demand":"","note":"1-3句大白话","children":[]}。生成 3~6 个子节点，最多再嵌一层，总共 ≤10 个节点。`;

  const user = `整棵导图的主题：${map.topic}（${typeLabel(map.type)}）
节点在树中的位置（缩进表示层级）：
${chain}

该节点已有子节点：${siblings}

${q}`;

  return { system, user };
}

function audienceLabelOf(map) {
  const a = AUDIENCES.find((x) => x.id === map.audience);
  return a ? a.label : '纯初学者';
}

